//
// A drop is the one place in Pyxis where the person encrypting and the person
// decrypting are different people who never meet: a stranger with the public
// link seals files to a key whose private half exists only in the owner's
// fragment. That is a key encapsulation problem, and the symmetric schedule in
// e2e.js cannot express it.
//
//   X-Wing = ML-KEM-768 (FIPS 203) + X25519, combined with the fixed combiner
//   of draft-connolly-cfrg-xwing-kem. It is secure if EITHER primitive is, so
//   its strength is the stronger leg's: ML-KEM-768 is NIST category 3 (~AES-192,
//   ~181-bit classical core-SVP), comfortably past RSA-4096's ~150 bits, and
//   unlike RSA it does not go to zero against a quantum computer.
//
//   seed (private key)   32 bytes  ← the whole decapsulation key, so the owner's
//   public key         1216 bytes    link fragment stays 43 characters like
//   ciphertext         1120 bytes    every other link in this application
//   shared secret        32 bytes  → the root of a submission's key schedule
//
// WHY VENDORED. WebCrypto cannot do this yet: ML-KEM is in the WICG "Modern
// Algorithms" draft (encapsulateBits/decapsulateBits) and every major browser
// already speaks ML-KEM in its TLS stack, but none exposes it to script. So the
// implementation ships with the page, the way qrlib.js does. When the API
// lands, e2e.js can feature-detect it and this file becomes dead weight — which
// is why nothing outside dropKem() in e2e.js touches window.PYXIS_KEM.
